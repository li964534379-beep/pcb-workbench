import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { createWorkbench } from '../server.mjs';

test('聊天模型选择：真实 HTTP 列表、指定模型、连接切换及密钥保留', async t => {
  const requests = [];
  let listCalls = 0;
  let releaseList;
  let holdList = false;
  let listStarted;
  const remote = createServer(async (request, response) => {
    if (request.url.endsWith('/models')) {
      listCalls += 1;
      if (request.url.startsWith('/unsupported')) { response.writeHead(404); response.end('{}'); return; }
      if (holdList) { listStarted(); await new Promise(resolve => { releaseList = resolve; }); }
      response.writeHead(200, { 'Content-Type': 'application/json' });
      response.end(JSON.stringify({ data: [{ id: 'fixture-alpha' }, { id: 'fixture-beta' }, { id: 'fixture-beta' }, { wrong: true }] }));
      return;
    }
    let body = '';
    for await (const chunk of request) body += chunk;
    const payload = JSON.parse(body);
    requests.push({ model: payload.model, authenticated: request.headers.authorization === 'Bearer qa-placeholder' });
    response.writeHead(200, { 'Content-Type': 'application/json' });
    response.end(JSON.stringify({ choices: [{ finish_reason: 'stop', message: { content: JSON.stringify({ status: 'proposal', reply: '可生成 5V 红色 LED 指示板，推荐 330 Ω。', voltage: 5, ledColor: 'red', resistance: 330, resistanceSource: 'recommended' }) } }] }));
  });
  await new Promise(resolve => remote.listen(0, '127.0.0.1', resolve));
  const baseUrl = `http://127.0.0.1:${remote.address().port}/v1`;
  const dataDirectory = await mkdtemp(join(tmpdir(), 'pcb-models-qa-'));
  const { server, store } = await createWorkbench({ dataDirectory, model: { provider: 'api', baseUrl, model: 'fixture-alpha', apiKey: 'qa-placeholder' } });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await Promise.all([new Promise(resolve => server.close(resolve)), new Promise(resolve => remote.close(resolve))]); });
  const origin = `http://127.0.0.1:${server.address().port}`;
  const post = async (path, payload) => {
    const response = await fetch(`${origin}${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(payload) });
    return { status: response.status, data: await response.json() };
  };
  const bootstrap = async () => (await (await fetch(`${origin}/api/bootstrap`)).json()).settings;
  let settings = await bootstrap();
  const originalConnection = settings.connectionId;
  assert.equal(listCalls, 0, '启动不自动请求远端列表');
  assert.ok(!JSON.stringify(settings).includes('qa-placeholder'));
  let result = await post('/api/models', { connectionId: settings.connectionId });
  assert.equal(result.status, 200);
  assert.deepEqual(result.data.models, ['fixture-alpha', 'fixture-beta']);
  assert.equal(listCalls, 1);
  await bootstrap();
  assert.equal(listCalls, 1, '读取已获取的模型列表不重复请求远端');
  const projects = await Promise.all([store.create(), store.create()]);
  const chats = await Promise.all(projects.map((project, index) => post(`/api/projects/${project.id}/chat`, { revision: 0, text: '5V 红色指示板，电阻请推荐', modelSelection: { provider: 'api', model: index ? 'fixture-beta' : 'fixture-alpha', connectionId: settings.connectionId } })));
  assert.deepEqual(chats.map(chat => chat.status), [200, 200]);
  assert.deepEqual(requests.map(request => request.model).sort(), ['fixture-alpha', 'fixture-beta']);
  assert.ok(requests.every(request => request.authenticated));
  assert.equal(chats[1].data.messages.at(-1).model, 'fixture-beta');
  assert.equal((await bootstrap()).model, 'fixture-alpha', '聊天选模型不覆盖其他会话的默认模型');
  assert.ok(!(await readFile(join(dataDirectory, projects[1].id, 'project.json'), 'utf8')).includes('qa-placeholder'));
  settings = (await post('/api/settings', { provider: 'codex' })).data;
  assert.equal(settings.hasApiKey, true);
  assert.equal(settings.baseUrl, baseUrl);
  assert.deepEqual(settings.models, ['fixture-alpha', 'fixture-beta']);
  settings = (await post('/api/settings', { provider: 'api', baseUrl, model: 'fixture-beta' })).data;
  assert.equal(settings.hasApiKey, true);
  assert.equal(listCalls, 1, '切换执行方式不获取列表或请求模型');
  const stale = await post(`/api/projects/${projects[0].id}/chat`, { revision: 0, text: '接着讨论', modelSelection: { provider: 'api', model: 'fixture-alpha', connectionId: originalConnection } });
  assert.equal(stale.status, 422);
  assert.equal(requests.length, 2, '失效连接不能把请求发到新连接');
  const invalid = await post('/api/settings', { provider: 'api', baseUrl: `${baseUrl}/chat/completions`, model: 'fixture-alpha' });
  assert.equal(invalid.status, 422);
  assert.match(invalid.data.error, /基础地址/);
  holdList = true;
  const started = new Promise(resolve => { listStarted = resolve; });
  const pending = post('/api/models', { connectionId: settings.connectionId });
  await started;
  settings = (await post('/api/settings', { provider: 'api', baseUrl: `${baseUrl}/changed`, model: 'manual-model' })).data;
  releaseList();
  assert.equal((await pending).status, 422, '旧连接返回的模型列表不能覆盖新连接');
  assert.deepEqual((await bootstrap()).models, ['manual-model']);
  assert.equal(settings.hasApiKey, false, '更换 API 地址不继承密钥');
  holdList = false;
  settings = (await post('/api/settings', { provider: 'api', baseUrl: `http://127.0.0.1:${remote.address().port}/unsupported`, model: 'manual-model', apiKey: 'qa-placeholder' })).data;
  const unsupportedList = await post('/api/models', { connectionId: settings.connectionId });
  assert.equal(unsupportedList.status, 422);
  assert.match(unsupportedList.data.error, /手动/);
  const manualChat = await post(`/api/projects/${projects[0].id}/chat`, { revision: 0, text: '还是用红色 LED 指示板', modelSelection: { provider: 'api', model: 'manual-model', connectionId: settings.connectionId } });
  assert.equal(manualChat.status, 200);
  assert.equal(requests.at(-1).model, 'manual-model');
  settings = (await post('/api/settings', { provider: 'api', baseUrl: settings.baseUrl, model: 'manual-model', clearApiKey: true })).data;
  assert.equal(settings.hasApiKey, false);
  assert.equal(requests.length, 3);
  result = await post('/api/settings', { provider: 'api', baseUrl, model: '' });
  assert.equal(result.status, 200, '只填写连接地址即可先获取模型，不必猜模型名称');
  settings = result.data;
  assert.equal(settings.apiConfigured, true);
  assert.equal(settings.model, '');
  result = await post('/api/models', { connectionId: settings.connectionId });
  assert.equal(result.status, 200);
  assert.deepEqual(result.data.models, ['fixture-alpha', 'fixture-beta']);
  const chosen = await post(`/api/projects/${projects[0].id}/chat`, { revision: 0, text: '按已知条件继续讨论', modelSelection: { provider: 'api', model: 'fixture-beta', connectionId: settings.connectionId } });
  assert.equal(chosen.status, 200);
  assert.equal(requests.at(-1).model, 'fixture-beta');
  assert.equal((await bootstrap()).model, '', '无需更改默认模型也可在聊天页选用列表模型');
  const invalidCredential = 'qa-private-header\nwrapped';
  settings = (await post('/api/settings', { provider: 'api', baseUrl, model: 'fixture-beta', apiKey: invalidCredential })).data;
  const invalidHeader = await post(`/api/projects/${projects[0].id}/chat`, { revision: 0, text: '验证格式错误的密钥不会被回显', modelSelection: { provider: 'api', model: 'fixture-beta', connectionId: settings.connectionId } });
  assert.equal(invalidHeader.status, 422);
  assert.ok(!invalidHeader.data.error.includes('qa-private-header'), '网络异常信息不得回显密钥');
  assert.equal(requests.length, 4, '本地格式错误不应触发远端模型调用');
  t.diagnostic(JSON.stringify({ listCalls, modelCalls: requests.length, selectedModels: requests.map(request => request.model) }));
});
