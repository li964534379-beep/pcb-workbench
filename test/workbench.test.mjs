import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createServer } from 'node:http';
import { mkdtemp, readFile, readdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { unzipSync, zipSync, strFromU8, strToU8 } from 'fflate';
import { createWorkbench } from '../server.mjs';

test('H5 工程流程：两次确认、真实检查、原生导回续改及旧版本保留', { timeout: 120000 }, async t => {
  const dataDirectory = await mkdtemp(join(tmpdir(), 'pcb-workbench-qa-'));
  let calls = 0;
  const prompts = [];
  const model = createServer(async (request, response) => {
    let body = '';
    for await (const chunk of request) body += chunk;
    const payload = JSON.parse(body);
    prompts.push(payload.messages.at(-1).content);
    const editing = payload.messages.at(-1).content.includes('"reference"');
    const target = payload.messages.at(-1).content.includes('680') ? 680 : 470;
    calls += 1;
    response.writeHead(200, { 'Content-Type': 'application/json' });
    const result = editing
      ? { status: 'proposal', reply: `只调整 R1 为 ${target} Ω。`, reference: 'R1', resistance: target }
      : { status: 'proposal', reply: '建议用 330 Ω，确认后生成 5V 红色 LED 指示板。', voltage: 5, ledColor: 'red', resistance: 330, resistanceSource: 'recommended' };
    response.end(JSON.stringify({ choices: [{ message: { content: JSON.stringify(result) }, finish_reason: 'stop' }] }));
  });
  await new Promise(resolve => model.listen(0, '127.0.0.1', resolve));
  const { server, store } = await createWorkbench({ dataDirectory, model: { provider: 'api', baseUrl: `http://127.0.0.1:${model.address().port}/v1`, model: 'fixture' } });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await Promise.all([new Promise(resolve => server.close(resolve)), new Promise(resolve => model.close(resolve))]); });
  const origin = `http://127.0.0.1:${server.address().port}`;
  async function post(path, payload) {
    const response = await fetch(`${origin}${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(payload) });
    const data = await response.json();
    return { status: response.status, data };
  }
  const mark = performance.now();
  let project = (await post('/api/projects', {})).data;
  assert.equal((await post(`/api/projects/${project.id}/confirm`, { revision: 0 })).status, 422);
  assert.equal((await store.load(project.id)).revision, 0);
  project = (await post(`/api/projects/${project.id}/chat`, { revision: 0, text: '做 5V 红色指示灯，电阻请推荐。' })).data;
  assert.equal(calls, 1);
  assert.equal((await post(`/api/projects/${project.id}/confirm`, { revision: 0, proposalId: 'old-proposal' })).status, 422);
  let result = await post(`/api/projects/${project.id}/confirm`, { revision: 0, proposalId: project.proposal.id });
  assert.equal(result.status, 200, JSON.stringify(result.data));
  project = result.data;
  assert.equal(project.revision, 1);
  assert.equal(project.stage, 'schematic');
  assert.equal(project.checks.erc.passed, true);
  assert.equal((await fetch(`${origin}/api/projects/${project.id}/export?revision=1`)).status, 422);
  assert.equal((await readdir(store.revisionDirectory(project))).some(file => file.endsWith('.kicad_pcb')), false);
  project = (await post(`/api/projects/${project.id}/chat`, { revision: 1, text: '把原理图里的 R1 改为 470 欧姆。' })).data;
  assert.match(prompts.at(-1), /尚未生成 PCB/);
  assert.ok(!prompts.at(-1).includes('从原理图和 PCB 读到一致'));
  const staleEditId = project.editProposal.id;
  await post(`/api/projects/${project.id}/resistance`, { revision: 1, resistance: 330 });
  assert.equal((await post(`/api/projects/${project.id}/confirm`, { revision: 1, proposalId: staleEditId })).status, 422);
  assert.equal((await store.load(project.id)).stage, 'schematic', '失效的修改确认不得变成画板确认');
  assert.equal((await readdir(store.revisionDirectory(project))).some(file => file.endsWith('.kicad_pcb')), false);
  project = (await post(`/api/projects/${project.id}/resistance`, { revision: 1, resistance: 470 })).data;
  assert.equal(calls, 2, '明确输入元件值不调用模型');
  assert.equal(project.editProposal.edit.after, 470);
  project = (await post(`/api/projects/${project.id}/confirm`, { revision: 1, proposalId: project.editProposal.id })).data;
  assert.equal(project.revision, 2);
  assert.equal(project.stage, 'schematic');
  assert.equal(project.views.pcb, false);
  result = await post(`/api/projects/${project.id}/confirm`, { revision: 2, proposalId: 'schematic' });
  assert.equal(result.status, 200, JSON.stringify(result.data));
  project = result.data;
  assert.equal(project.revision, 3);
  assert.equal(project.views.components.find(part => part.ref === 'R1').value, '470R');
  assert.deepEqual([project.checks.erc.schematicIssues, project.checks.drc.boardIssues, project.checks.drc.unconnected, project.checks.drc.parityIssues], [0, 0, 0, 0]);
  const generatedMs = performance.now() - mark;
  const archive = new Uint8Array(await (await fetch(`${origin}/api/projects/${project.id}/export?revision=3`)).arrayBuffer());
  const entries = unzipSync(archive);
  assert.ok(entries['Workbench.pretty/Resistor.kicad_mod']);
  assert.ok(!entries['workflow.json']);
  entries['led-indicator.kicad_sch'] = strToU8(strFromU8(entries['led-indicator.kicad_sch']).replace('"Value" "470R"', '"Value" "0.47kΩ"'));
  const board = strFromU8(entries['led-indicator.kicad_pcb']).replace('"5V LED"', '"KEEP HAND EDIT"').replace('"Value" "470R"', '"Value" "0.47kΩ"');
  const circle = `(gr_circle (center 38 16) (end 39 16) (stroke (width 0.05) (type default)) (fill none) (layer "Edge.Cuts") (uuid "${randomUUID()}"))`;
  entries['led-indicator.kicad_pcb'] = strToU8(board.slice(0, board.lastIndexOf(')')) + circle + ')\n');
  entries['manual.txt'] = strToU8('Retain user files.');
  entries['project.json'] = strToU8('{"userAddon":"retain"}');
  const changedBytes = zipSync(entries);
  const upload = await fetch(`${origin}/api/import?name=manual.zip`, { method: 'POST', headers: { 'Content-Type': 'application/zip' }, body: changedBytes });
  let imported = await upload.json();
  assert.equal(upload.status, 200, JSON.stringify(imported));
  assert.equal(imported.checks.drc.passed, true);
  const oldDirectory = store.revisionDirectory(imported);
  const original = await readFile(join(oldDirectory, 'led-indicator.kicad_pcb'), 'utf8');
  imported = (await post(`/api/projects/${imported.id}/chat`, { revision: 1, text: '只把 R1 改为 680 欧姆。' })).data;
  assert.ok(imported.editProposal, JSON.stringify(imported));
  assert.equal(imported.editProposal.edit.after, 680);
  assert.equal(calls, 3);
  const confirmPayload = { revision: 1, proposalId: imported.editProposal.id };
  const concurrent = await Promise.all([post(`/api/projects/${imported.id}/confirm`, confirmPayload), post(`/api/projects/${imported.id}/confirm`, confirmPayload)]);
  assert.deepEqual(concurrent.map(item => item.status).sort(), [200, 422]);
  imported = concurrent.find(item => item.status === 200).data;
  assert.equal(imported.revision, 2);
  assert.equal(imported.checks.drc.passed, true);
  const edited = await readFile(join(store.revisionDirectory(imported), 'led-indicator.kicad_pcb'), 'utf8');
  assert.equal(edited.replace('"Value" "680R"', '"Value" "0.47kΩ"'), original);
  assert.equal(await readFile(join(oldDirectory, 'led-indicator.kicad_pcb'), 'utf8'), original);
  assert.equal(await readFile(join(store.revisionDirectory(imported), 'manual.txt'), 'utf8'), 'Retain user files.');
  assert.equal(await readFile(join(store.revisionDirectory(imported), 'project.json'), 'utf8'), '{"userAddon":"retain"}');
  const cleanReport = await post(`/api/projects/${imported.id}/explain`, { revision: 2 });
  assert.equal(cleanReport.data.explanation.totalIssues, 0);
  assert.equal(calls, 3, '生成、布线、导入、属性编辑、写回、导出及零问题报告均不调用模型');
  assert.equal((await post(`/api/projects/${imported.id}/confirm`, confirmPayload)).status, 422);
  const unsafe = zipSync({ '../outside.txt': strToU8('bad') });
  const rejected = await fetch(`${origin}/api/import?name=unsafe.zip`, { method: 'POST', headers: { 'Content-Type': 'application/zip' }, body: unsafe });
  assert.equal(rejected.status, 422);
  assert.match((await rejected.json()).error, /路径/);
  const mismatchEntries = { ...entries, 'led-indicator.kicad_pcb': strToU8(original.replace('"Value" "0.47kΩ"', '"Value" "680R"')) };
  const mismatch = await fetch(`${origin}/api/import?name=mismatch.zip`, { method: 'POST', headers: { 'Content-Type': 'application/zip' }, body: zipSync(mismatchEntries) });
  assert.equal(mismatch.status, 422);
  assert.match((await mismatch.json()).error, /不一致/);
  assert.equal((await store.list()).length, 2, '无效导入不进入工程列表');
  const cut = original.replace(/\(segment \(start 6 10\.54\) \(end 34 10\.54\) \(width 0\.4\) \(layer "B\.Cu"\) \(net 3\) \(uuid "[^"]+"\)\)/, '');
  assert.notEqual(cut, original, '故障注入应只切断 GND 走线');
  const cutEntries = { ...entries, 'led-indicator.kicad_pcb': strToU8(cut), 'drc.json': new Uint8Array(await readFile(join(store.revisionDirectory(project), 'drc.json'))) };
  const brokenResponse = await fetch(`${origin}/api/import?name=broken.zip`, { method: 'POST', headers: { 'Content-Type': 'application/zip' }, body: zipSync(cutEntries) });
  const broken = await brokenResponse.json();
  assert.equal(brokenResponse.status, 200, JSON.stringify(broken));
  assert.equal(broken.checks.drc.passed, false);
  assert.equal(broken.checks.drc.unconnected, 1, '必须重新检查导回文件，不能沿用 ZIP 中的旧通过报告');
  assert.equal((await fetch(`${origin}/api/projects/${broken.id}/export?revision=1`)).status, 422);
  const settingsResult = await post('/api/settings', { provider: 'api', baseUrl: 'http://127.0.0.1:1/v1', model: 'fixture', apiKey: 'qa-placeholder' });
  assert.equal(settingsResult.data.hasApiKey, true);
  assert.ok(!JSON.stringify(settingsResult.data).includes('qa-placeholder'));
  const changedEndpoint = await post('/api/settings', { provider: 'api', baseUrl: 'http://127.0.0.1:2/v1', model: 'fixture' });
  assert.equal(changedEndpoint.data.hasApiKey, false, '更换 API 地址不继承旧地址的密钥');
  const foreignOrigin = await fetch(`${origin}/api/projects`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://unrelated.example' }, body: '{}' });
  assert.equal(foreignOrigin.status, 403);
  t.diagnostic(JSON.stringify({ dataDirectory, generatedMs: Math.round(generatedMs), modelCalls: calls, archiveBytes: archive.length }));
});
